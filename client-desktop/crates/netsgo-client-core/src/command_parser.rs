use serde::{Deserialize, Serialize};

/// Extracted connection parameters from any NetsGo server onboarding snippet:
/// 1. `netsgo client --server '...' --key '...' [--tls-skip-verify] [--tls-fingerprint ...]`
/// 2. `curl -fsSL .../install.sh | sh -s -- --client --server '...' --key '...'`
/// 3. `docker run ... -e NETSGO_SERVER='...' -e NETSGO_KEY='...' ...`
/// 4. `docker-compose.yml` (`NETSGO_SERVER: "..."`, `NETSGO_KEY: "..."`)
/// 5. Inline env vars: `NETSGO_SERVER=https://... NETSGO_KEY=... netsgo client`
#[derive(Debug, Clone, Default, PartialEq, Eq, Serialize, Deserialize)]
pub struct ParsedConnectCommand {
    pub server: Option<String>,
    pub key: Option<String>,
    pub tls_skip_verify: bool,
    pub tls_fingerprint: Option<String>,
}

impl ParsedConnectCommand {
    pub fn is_complete(&self) -> bool {
        self.server.as_deref().is_some_and(|s| !s.trim().is_empty())
            && self.key.as_deref().is_some_and(|k| !k.trim().is_empty())
    }

    pub fn has_any(&self) -> bool {
        self.server.is_some()
            || self.key.is_some()
            || self.tls_skip_verify
            || self.tls_fingerprint.is_some()
    }
}

/// Parses shell commands, curl install snippets, Docker run commands, or Docker
/// Compose YAML snippets generated by the NetsGo server panel.
pub fn parse_connect_command(input: &str) -> Option<ParsedConnectCommand> {
    let trimmed = input.trim();
    if trimmed.is_empty() {
        return None;
    }

    let mut out = ParsedConnectCommand::default();

    // 1. Check YAML / line-based key: value pairs first (e.g. docker-compose.yml)
    parse_yaml_env_lines(trimmed, &mut out);

    // 2. Tokenize shell words (handling `\ + newline` continuations, `'...'`, `"..."`)
    let tokens = shell_tokenize(trimmed);
    let mut i = 0;
    while i < tokens.len() {
        let tok = tokens[i].as_str();

        if tok == "--server" || tok == "-s" {
            if let Some(val) = tokens.get(i + 1) {
                set_if_non_empty(&mut out.server, val);
                i += 2;
                continue;
            }
        } else if let Some(val) = tok
            .strip_prefix("--server=")
            .or_else(|| tok.strip_prefix("-s="))
        {
            set_if_non_empty(&mut out.server, val);
        } else if tok == "--key" || tok == "-k" {
            if let Some(val) = tokens.get(i + 1) {
                set_if_non_empty(&mut out.key, val);
                i += 2;
                continue;
            }
        } else if let Some(val) = tok
            .strip_prefix("--key=")
            .or_else(|| tok.strip_prefix("-k="))
        {
            set_if_non_empty(&mut out.key, val);
        } else if tok == "--tls-skip-verify" {
            out.tls_skip_verify = true;
        } else if let Some(val) = tok.strip_prefix("--tls-skip-verify=") {
            out.tls_skip_verify = matches!(val.to_ascii_lowercase().as_str(), "1" | "true" | "yes");
        } else if tok == "--tls-fingerprint" {
            if let Some(val) = tokens.get(i + 1) {
                set_if_non_empty(&mut out.tls_fingerprint, val);
                i += 2;
                continue;
            }
        } else if let Some(val) = tok.strip_prefix("--tls-fingerprint=") {
            set_if_non_empty(&mut out.tls_fingerprint, val);
        } else if tok == "-e" || tok == "--env" {
            if let Some(env_pair) = tokens.get(i + 1) {
                parse_env_assignment(env_pair, &mut out);
                i += 2;
                continue;
            }
        } else if let Some(env_pair) = tok.strip_prefix("--env=") {
            parse_env_assignment(env_pair, &mut out);
        } else if tok.contains('=') && !tok.starts_with('-') && !tok.contains("://") {
            parse_env_assignment(tok, &mut out);
        } else if tok.contains("://") && out.server.is_none() && tokens.len() == 1 {
            // Bare URL pasted directly
            set_if_non_empty(&mut out.server, tok);
        }

        i += 1;
    }

    out.has_any().then_some(out)
}

fn set_if_non_empty(slot: &mut Option<String>, raw: &str) {
    let cleaned = raw.trim();
    if !cleaned.is_empty() {
        *slot = Some(cleaned.to_string());
    }
}

fn parse_env_assignment(pair: &str, out: &mut ParsedConnectCommand) {
    let Some((k, v)) = pair.split_once('=') else {
        return;
    };
    let key = k.trim();
    let val = unquote_scalar(v.trim());
    match key {
        "NETSGO_SERVER" => set_if_non_empty(&mut out.server, &val),
        "NETSGO_KEY" => set_if_non_empty(&mut out.key, &val),
        "NETSGO_TLS_SKIP_VERIFY" => {
            out.tls_skip_verify = matches!(val.to_ascii_lowercase().as_str(), "1" | "true" | "yes");
        }
        "NETSGO_TLS_FINGERPRINT" => set_if_non_empty(&mut out.tls_fingerprint, &val),
        _ => {}
    }
}

fn parse_yaml_env_lines(input: &str, out: &mut ParsedConnectCommand) {
    for raw_line in input.lines() {
        let line = raw_line.trim();
        if line.starts_with('#') || line.is_empty() {
            continue;
        }
        let line = line.strip_prefix('-').map(str::trim).unwrap_or(line);
        for (prefix, target) in [
            ("NETSGO_SERVER:", true),
            ("NETSGO_KEY:", false),
            ("NETSGO_TLS_FINGERPRINT:", false),
            ("NETSGO_TLS_SKIP_VERIFY:", false),
        ] {
            let _ = target;
            if let Some(rest) = line.strip_prefix(prefix) {
                let val = unquote_scalar(rest.trim());
                match prefix {
                    "NETSGO_SERVER:" => set_if_non_empty(&mut out.server, &val),
                    "NETSGO_KEY:" => set_if_non_empty(&mut out.key, &val),
                    "NETSGO_TLS_FINGERPRINT:" => set_if_non_empty(&mut out.tls_fingerprint, &val),
                    "NETSGO_TLS_SKIP_VERIFY:" => {
                        out.tls_skip_verify =
                            matches!(val.to_ascii_lowercase().as_str(), "1" | "true" | "yes");
                    }
                    _ => {}
                }
            }
        }
    }
}

fn unquote_scalar(raw: &str) -> String {
    let s = raw.trim();
    if s.len() >= 2 && s.starts_with('"') && s.ends_with('"') {
        let inner = &s[1..s.len() - 1];
        return inner.replace("\\\"", "\"").replace("\\\\", "\\");
    }
    if s.len() >= 2 && s.starts_with('\'') && s.ends_with('\'') {
        let inner = &s[1..s.len() - 1];
        return inner.replace("'\"'\"'", "'");
    }
    s.to_string()
}

/// POSIX-style tokenizer supporting `'...'` (including `'foo'"'"'bar'`), `"..."`,
/// backslash escapes, and `\<newline>` line continuations.
fn shell_tokenize(input: &str) -> Vec<String> {
    let mut tokens = Vec::new();
    let mut current = String::new();
    let mut in_token = false;

    #[derive(Clone, Copy, PartialEq, Eq)]
    enum Quote {
        None,
        Single,
        Double,
    }

    let mut quote = Quote::None;
    let mut chars = input.chars().peekable();

    while let Some(ch) = chars.next() {
        match quote {
            Quote::None => match ch {
                '\'' => {
                    quote = Quote::Single;
                    in_token = true;
                }
                '"' => {
                    quote = Quote::Double;
                    in_token = true;
                }
                '\\' => match chars.peek().copied() {
                    Some('\n') => {
                        chars.next();
                    }
                    Some('\r') => {
                        chars.next();
                        if chars.peek() == Some(&'\n') {
                            chars.next();
                        }
                    }
                    Some(next) => {
                        current.push(next);
                        in_token = true;
                        chars.next();
                    }
                    None => {}
                },
                '#' if !in_token => {
                    for c in chars.by_ref() {
                        if c == '\n' {
                            break;
                        }
                    }
                }
                c if c.is_whitespace() => {
                    if in_token {
                        tokens.push(std::mem::take(&mut current));
                        in_token = false;
                    }
                }
                '|' | ';' | '&' => {
                    if in_token {
                        tokens.push(std::mem::take(&mut current));
                        in_token = false;
                    }
                }
                c => {
                    current.push(c);
                    in_token = true;
                }
            },
            Quote::Single => {
                if ch == '\'' {
                    quote = Quote::None;
                } else {
                    current.push(ch);
                }
            }
            Quote::Double => match ch {
                '"' => {
                    quote = Quote::None;
                }
                '\\' => match chars.peek().copied() {
                    Some('\n') => {
                        chars.next();
                    }
                    Some(next @ ('"' | '\\' | '$' | '`')) => {
                        current.push(next);
                        chars.next();
                    }
                    _ => current.push('\\'),
                },
                c => current.push(c),
            },
        }
    }

    if in_token {
        tokens.push(current);
    }

    tokens
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn parses_direct_netsgo_client_command() {
        let cmd = "\
netsgo client \\\n  \
  --server 'https://edge.example.com:9527' \\\n  \
  --key 'ngk_live_9876543210abcdef'";
        let parsed = parse_connect_command(cmd).expect("should parse");
        assert_eq!(
            parsed.server.as_deref(),
            Some("https://edge.example.com:9527")
        );
        assert_eq!(parsed.key.as_deref(), Some("ngk_live_9876543210abcdef"));
        assert!(parsed.is_complete());
    }

    #[test]
    fn parses_curl_install_and_run_command_with_channel_and_escaped_quotes() {
        let cmd = "\
curl -fsSL https://raw.githubusercontent.com/zsio/netsgo/main/scripts/install.sh | sh -s -- \\\n  \
  --channel beta \\\n  \
  --client \\\n  \
  --server 'https://hk.example.com:8443' \\\n  \
  --key 'k_with_'\"'\"'quote'";
        let parsed = parse_connect_command(cmd).expect("should parse");
        assert_eq!(
            parsed.server.as_deref(),
            Some("https://hk.example.com:8443")
        );
        assert_eq!(parsed.key.as_deref(), Some("k_with_'quote"));
    }

    #[test]
    fn parses_docker_run_command() {
        let cmd = "\
docker run -d \\\n  \
  --name netsgo-client \\\n  \
  --restart unless-stopped \\\n  \
  --network host \\\n  \
  -e NETSGO_SERVER='https://docker.example.com' \\\n  \
  -e NETSGO_KEY='ngk_docker_secret' \\\n  \
  zsio/netsgo:latest client --data-dir /var/lib/netsgo";
        let parsed = parse_connect_command(cmd).expect("should parse");
        assert_eq!(
            parsed.server.as_deref(),
            Some("https://docker.example.com")
        );
        assert_eq!(parsed.key.as_deref(), Some("ngk_docker_secret"));
    }

    #[test]
    fn parses_docker_compose_yaml() {
        let yaml = r#"
services:
  netsgo-client:
    image: zsio/netsgo:latest
    environment:
      NETSGO_SERVER: "https://compose.example.com:9527"
      NETSGO_KEY: "ngk_compose_key"
"#;
        let parsed = parse_connect_command(yaml).expect("should parse");
        assert_eq!(
            parsed.server.as_deref(),
            Some("https://compose.example.com:9527")
        );
        assert_eq!(parsed.key.as_deref(), Some("ngk_compose_key"));
    }

    #[test]
    fn parses_tls_flags_and_equals_syntax() {
        let cmd = "netsgo client --server=https://10.0.0.2:9527 --key=mykey --tls-skip-verify --tls-fingerprint=AA:BB:CC";
        let parsed = parse_connect_command(cmd).expect("should parse");
        assert_eq!(parsed.server.as_deref(), Some("https://10.0.0.2:9527"));
        assert_eq!(parsed.key.as_deref(), Some("mykey"));
        assert!(parsed.tls_skip_verify);
        assert_eq!(parsed.tls_fingerprint.as_deref(), Some("AA:BB:CC"));
    }
}
